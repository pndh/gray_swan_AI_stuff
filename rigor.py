def _provider_kwargs(provider: str | None) -> dict:
    if provider == "deepseek":
        return {"base_url": bon.DEEPSEEK_URL,
                "api_key": os.environ.get("DEEPSEEK_API_KEY") or os.environ.get("NVIDIA_API_KEY")}
    if provider == "nvidia":
        return {"base_url": None, "api_key": bon.load_api_key()}
    return {"base_url": None, "api_key": None}


